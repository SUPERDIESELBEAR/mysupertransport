function unionMembers(spec: PortalSpec): string[] {
  const src = readSource(spec.unionFile);
  const m = src.match(spec.unionPattern);
  if (!m) return [];
  return [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1]);
}

function corpus(spec: PortalSpec): string {
  return spec.files.map(readSource).join("\n");
}

function esc(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\-]/g, "\\$&");
}

function hasRenderBranch(text: string, spec: PortalSpec, view: string): boolean {
  const v = esc(view);
  if (new RegExp(`case\\s+'${v}'\\s*:`).test(text)) return true;
  return spec.stateVars.some((sv) =>
    new RegExp(`\\b${sv}\\s*===\\s*'${v}'`).test(text),
  );
}

function hasWayIn(text: string, spec: PortalSpec, view: string): boolean {
  const v = esc(view);
  if (spec.setters.some((fn) => new RegExp(`\\b${fn}\\(\\s*'${v}'`).test(text))) {
    return true;
  }
  return spec.navKeys.some((k) => new RegExp(`\\b${k}:\\s*'${v}'`).test(text));
}

/**
 * THE FAILURE MESSAGE IS THE PRODUCT. Names what was searched, which halves
 * came back empty, and the three exits — written for someone who did not build
 * the guard.
 */
function explain(
  spec: PortalSpec,
  view: string,
  render: boolean,
  wayIn: boolean,
): string {
  const missing = [!render && "NO RENDER BRANCH", !wayIn && "NO WAY IN"]
    .filter(Boolean)
    .join(" and ");
  return [
    ``,
    `${spec.portal} portal: view '${view}' is declared but ${missing}.`,
    ``,
    `Searched in ${spec.files.join(", ")}:`,
    `  render branch  ${spec.stateVars.map((s) => `${s} === '${view}'`).join("  ")}`,
    `                 case '${view}':                                  ${render ? "FOUND" : "(0)"}`,
    `  way in         ${spec.navKeys.map((k) => `${k}: '${view}'`).join("  ")}`,
    `                 ${spec.setters.map((s) => `${s}('${view}')`).join("  ")}   ${wayIn ? "FOUND" : "(0)"}`,
    ``,
    `To make this pass, do ONE of these:`,
    `  1. WIRE IT. A view needs BOTH halves: a nav item (or a setter call from`,
    `     the screen that opens it) AND a render branch. An entry in the type`,
    `     or in ALLOWED_VIEWS is neither — that is how 'Driver App Preview'`,
    `     shipped unreachable three times, the last as a bare import whose own`,
    `     comment claimed the placement.`,
    `  2. DELETE IT. Remove the value from the union and from ALLOWED_VIEWS. A`,
    `     view nobody can reach and nobody renders is dead weight that reads as`,
    `     done.`,
    `  3. ALLOWLIST IT, WITH A REASON — only if it is a drill-down or a deep`,
    `     link. Add to KNOWN_NO_NAV_ENTRIES in src/test/view-reachability.test.ts`,
    `     as { portal: '${spec.portal}', view: '${view}', reason: 'DRILLDOWN <what opens it>' }`,
    `     and raise KNOWN_NO_NAV_MAX by exactly one. Note this exit only covers`,
    `     a MISSING NAV ITEM. A missing render branch is never allowlistable —`,
    `     the page would show nothing.`,
  ].join("\n");
}

const allowed = new Set(KNOWN_NO_NAV_ENTRIES.map((e) => `${e.portal}::${e.view}`));

describe("portal view reachability — every declared view can be reached", () => {
  it("every allowlist entry carries a written reason", () => {
    const bad = KNOWN_NO_NAV_ENTRIES.filter(
      (e) => !/^(DRILLDOWN|DEEPLINK|FALLBACK) \S/.test(e.reason),
    );
    expect(
      bad.map((e) => `${e.portal}::${e.view}`),
      "Every KNOWN_NO_NAV_ENTRIES reason must start with 'DRILLDOWN ' (name what " +
        "opens it) or 'DEEPLINK ' (name what generates the link). A bare list of " +
        "names is a place to hide things.",
    ).toEqual([]);
  });

  it("the allowlist may only shrink", () => {
    expect(
      KNOWN_NO_NAV_ENTRIES.length,
      `KNOWN_NO_NAV_ENTRIES has ${KNOWN_NO_NAV_ENTRIES.length} entries but ` +
        `KNOWN_NO_NAV_MAX is ${KNOWN_NO_NAV_MAX}.`,
    ).toBeLessThanOrEqual(KNOWN_NO_NAV_MAX);
  });

  it("each portal's view union was actually found and parsed", () => {
    const empty = PORTALS.filter((p) => unionMembers(p).length === 0).map(
      (p) => `${p.portal} (${p.unionFile})`,
    );
    expect(
      empty,
      "A portal's view union could not be parsed, so this guard searched " +
        "nothing for it and would report green having checked nothing. Fix the " +
        "unionPattern in PORTALS — do not delete the portal from the list.",
    ).toEqual([]);
  });

  it("every declared view has a render branch and a way in", () => {
    const failures: string[] = [];
    const ids: string[] = [];

    for (const spec of PORTALS) {
      const text = corpus(spec);
      for (const view of unionMembers(spec)) {
        const render = hasRenderBranch(text, spec, view);
        const wayIn = hasWayIn(text, spec, view);
        if (render && wayIn) continue;
        if (allowed.has(`${spec.portal}::${view}`)) continue;
        ids.push(`${spec.portal}::${view}`);
        failures.push(explain(spec, view, render, wayIn));
      }
    }

    expect(
      ids,
      `${ids.length} declared view(s) cannot be reached or cannot render.\n` +
        `EXPECTED RED: this guard shipped on 2026-09-10 with 1 known finding ` +
        `(management 'app-errors'). Do not make it pass by allowlisting it.\n` +
        failures.join("\n" + "-".repeat(74) + "\n"),
    ).toEqual([]);
  });
});
