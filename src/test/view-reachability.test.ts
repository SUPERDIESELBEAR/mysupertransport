/**
 * PORTAL VIEW REACHABILITY — can a user actually GET to the page?
 *
 * The four portals are single pages that fake sub-routing internally: a `view`
 * state variable, a union type listing its legal values, an allow-list, a nav
 * array, and a render branch per value. Nothing keeps those five in step.
 *
 * `Driver App Preview` shipped unreachable THREE times: built only into Staff;
 * then moved within Staff while the written directions still pointed at its old
 * location; then imported into Management with no nav item, no route and no
 * render — an unused import whose own comment claimed the placement. An import
 * is not a placement. The standing rule is that a page is not complete until
 * its navigation placement is written down AND IMPLEMENTED, and implemented
 * means a user can reach it.
 *
 * This guard asserts both halves for every declared view: A RENDER BRANCH and
 * A WAY IN.
 *
 * THIS GUARD IS EXPECTED TO BE RED. It ships with one real finding. Green is
 * reached by wiring or deleting the view — never by allowlisting a finding.
 */

/**
 * ALLOWLIST — deep-link and drill-down views, each with a WRITTEN REASON.
 *
 * A reason must start with:
 *   DRILLDOWN — opened from a row click or another view, never from the
 *               sidebar. NAME what opens it.
 *   DEEPLINK  — reached only from a generated URL (an email, a notification).
 *               NAME what generates the link.
 *   FALLBACK  — rendered as a default/else branch, so no `view === 'x'` exists
 *               to find. CITE the file and line that renders it. This is the
 *               only prefix that may excuse a missing RENDER BRANCH, and only
 *               after reading the source.
 *
 * Seeded 2026-09-10 from the reachability sweep: every entry below was
 * classified LEGITIMATE. Nothing the sweep called ORPHANED is here.
 * This list may only SHRINK.
 */
