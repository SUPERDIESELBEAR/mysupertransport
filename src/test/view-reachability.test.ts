/** Ceiling. Falls freely; rises only for a new entry carrying its reason. */
const KNOWN_NO_NAV_MAX = 10;

interface PortalSpec {
  readonly portal: string;
  /** File holding the view union. */
  readonly unionFile: string;
  /** Captures the body of the union declaration. */
  readonly unionPattern: RegExp;
  /** Files searched for render branches and ways in. */
  readonly files: readonly string[];
  /** State variables compared against a view value in a render branch. */
  readonly stateVars: readonly string[];
  /** Functions that navigate to a view. */
  readonly setters: readonly string[];
  /** Object keys used by the nav arrays to carry a view value. */
  readonly navKeys: readonly string[];
}

